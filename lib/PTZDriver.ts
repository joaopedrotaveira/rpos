class ReconnectingStream extends events.EventEmitter {
  hostname: string;
  port: number|string;
  stream: any = null; // the currently open network socket

  constructor() {
    super();
  }

  reconnect() {
    console.log("PTZ Driver - Reconnecting after error");
    this.connect(this.hostname, this.port);
  }

  connect(hostname: string, port: number|string) {
    this.hostname = hostname;
    this.port = port;

    this.stream = new net.Socket();
    
    this.stream.on('connect', () => {
      console.log('PTZ Driver - Socket connected');
      this.emit('connect');
    })
    this.stream.on('data', (data) => {  
        this.emit('data', data);
    });
    this.stream.on('close', () => {
      console.log('PTZ Driver - Socket closed');
      this.emit('close');
      // schedule a reconnect in 1 second (TODO - add backoff strategy)
      setTimeout(() => {this.reconnect()}, 1000); // use => to make timeout function bind to this instance
    });
    this.stream.on('error', () => {
      console.log('PTZ Driver - Socket error');
    });
    this.stream.on('timeout', () => {
      console.log('PTZ Driver - Socket timeout error');
    });

    console.log('PTZ Driver connecting to ' + this.hostname + ':' + this.port);
    this.stream.connect(this.port, this.hostname, () => {
      console.log('PTZ Driver has connected to ' + this.hostname + ':' + this.port);
    });

  }


  write(data: string|Buffer) {
    // pass the Write through to the socket. If the socket is null, we throw away the data
    try {
      this.stream.write(data);
    } catch (err) {
      console.log('PTZ Driver - Data thrown away')
    }
  }
}


class UDPStream extends events.EventEmitter {
  hostname: string;
  port: number|string;
  socket: any = null; // the currently open network socket

  constructor() {
    super();
  }

  connect(hostname: string, port: number|string) {
    this.hostname = hostname;
    this.port = port;

    this.socket = dgram.createSocket('udp4');
    
    this.socket.on('listening', () => {
      console.log('PTZ Driver - UDP Socket ready');
      this.emit('connect');
    })
    this.socket.on('message', (data) => {  
        this.emit('message', data);
    });
    this.socket.on('close', () => {
      console.log('PTZ Driver - UDP Socket closed');
    });
    this.socket.on('error', () => {
      console.log('PTZ Driver - UDP Socket error');
    });

    console.log('PTZ Driver connecting to ' + this.hostname + ':' + this.port);

    // Note - we could do a .connect() here that will bind this UDP socket to a hostname and port, which simplifies the .send() command
    // we get a "connected" event when the UDP socket is ready

    this.socket.bind(0); // let the OS pick the lock source port
  }


  write(data: string|Buffer) {
    // pass the Write through to the socket. If the socket is null, we throw away the data
    try {
      this.socket.send(data, this.port, this.hostname);
    } catch (err) {
      console.log('PTZ Driver - UDP Data thrown away')
    }
  }
}
class PTZDriver {

  config: rposConfig;
  rposAscii: any;
  tenx: any;
  pelcod: any;
  visca: any;
  panTiltHat: any;
  serialPort: any;
  stream: any;
  supportsAbsolutePTZ: boolean = false;
  supportsRelativePTZ: boolean = false;
  supportsContinuousPTZ: boolean = false;
  supportsGoToHome: boolean = false;
  hasFixedHomePosition: boolean = true;
  hasZoom: boolean = true;
  numPresets: number = 255;

  // rposascii v2. 'capabilities' is emitted when the controller sends caps and
  // 'presets' (string[]) when it lists the presets it has stored.
  events: events.EventEmitter = new events.EventEmitter();
  rposClient: RposAsciiClient = null;
  estimator: MotionEstimator = null;

  constructor(config: rposConfig) {

    // RPOS from mid 2022 supports multiple cameras and multiple PTZ addreses
    // so a new cameraAddress parameter is passed in the 'data' object
    this.config = config;
    let parent = this;

    // Sanity checks. Do not open serial or socket if using USB Tenx driver
    let PTZOutput = config.PTZOutput;
    if (config.PTZDriver === 'tenx') {
      PTZOutput = 'none';
    }

    // Sanity checks. Do not open serial or socket if using Pan-Tilt HAT
    if (config.PTZDriver === 'pan-tilt-hat') {
      PTZOutput = 'none';
    }


    if (config.PTZDriver === 'rposascii') {
      this.estimator = new MotionEstimator(Number(config.PTZEstimateMsPerUnit) || 1500);
      this.rposClient = new RposAsciiClient((line: string) => {
        try {
          this.stream.write(line);
        } catch (err) {
          // no stream open, or the write failed. Requests have timeouts, so drop it.
        }
      }, {
        statusMaxAgeMs: config.PTZStatusMaxAgeMs,
        requestTimeoutMs: config.PTZRequestTimeoutMs
      });
      this.rposClient.on('caps', (caps) => this.applyCaps(caps));
      this.rposClient.on('presets', (tokens) => this.events.emit('presets', tokens));
    }

    // Open the OUTPUT STREAM
    if (PTZOutput === 'serial') {
      const { SerialPort } = require('serialport');
      this.serialPort = new SerialPort({
        path: config.PTZSerialPort,
        baudRate: config.PTZSerialPortSettings.baudRate,
        parity:   config.PTZSerialPortSettings.parity,
        dataBits: config.PTZSerialPortSettings.dataBits,
        stopBits: config.PTZSerialPortSettings.stopBits,
      });

      this.serialPort.on("open", () => {
          console.log('Serial port opened');
          if (this.rposClient) this.rposClient.connected();
      });

      this.serialPort.on("data", (data) => {
          if (this.rposClient) this.rposClient.handleData(data);
      });

      this.serialPort.on("close", () => {
          if (this.rposClient) this.rposClient.disconnected();
      });

      this.serialPort.on("error", function(err: Error){
          console.log('Error: '+err);
      });

      this.stream = this.serialPort;
    }

    if (PTZOutput === 'tcp') {
      let host = config.PTZOutputURL.split(':')[0];
      let port = config.PTZOutputURL.split(':')[1];      

      this.stream = new ReconnectingStream();
      this.stream.on('data', (data) => {
          if (this.rposClient) this.rposClient.handleData(data);
          else console.log('PTZ Driver received socket data ' + data);
      });
      this.stream.on('connect', () => {
          if (this.rposClient) this.rposClient.connected();
      });
      this.stream.on('close', () => {
          if (this.rposClient) this.rposClient.disconnected();
      });

      console.log('PTZ Driver connecting to ' + host + ':' + port);

      this.stream.connect(host, port);
    }

    if (PTZOutput === 'udp') {
      let host = config.PTZOutputURL.split(':')[0];
      let port = config.PTZOutputURL.split(':')[1];      

      this.stream = new UDPStream();
      this.stream.on('message', (data) => {  // USES MESSAGE (tcp uses 'data')
          if (this.rposClient) this.rposClient.handleDatagram(data);
          else console.log('PTZ Driver received UDP socket data ' + data);
      });
      this.stream.on('connect', () => {
          if (this.rposClient) this.rposClient.connected();
      });

      console.log('PTZ Driver connecting to UDP ' + host + ':' + port);

      this.stream.connect(host, port);
    }

    // Initialise specific drivers, map them onto a STREAM

    if (config.PTZDriver === 'tenx') {
      var TenxDriver = require('tenx-usb-missile-launcher-driver');
      this.tenx = new TenxDriver();
      this.tenx.open();
      this.supportsContinuousPTZ = true;
    }

    if (config.PTZDriver === 'rposascii') {
      this.rposAscii = true;
      this.supportsAbsolutePTZ = true;
      this.supportsRelativePTZ = true;
      this.supportsContinuousPTZ = true;
      this.supportsGoToHome = true;
    }

    if (config.PTZDriver === 'pan-tilt-hat') {
      var PanTiltHAT = require('pan-tilt-hat');
      this.panTiltHat = new PanTiltHAT();
      this.supportsAbsolutePTZ = true;
      this.supportsRelativePTZ = true;
      this.supportsContinuousPTZ = true;
      this.supportsGoToHome = true;
    }
    
    if (config.PTZDriver === 'pelcod') {
      var PelcoD = require('node-pelcod');
      this.pelcod = new PelcoD(this.stream);
      this.pelcod.setAddress(parent.config.PTZCameraAddress);
      this.supportsContinuousPTZ = true;
      this.supportsGoToHome = true;
      this.hasFixedHomePosition = false;
      // numPrests - use default
    }

    if (config.PTZDriver === 'visca') {
      this.visca = true;
      this.supportsContinuousPTZ = true;
      this.supportsGoToHome = true;
      this.hasFixedHomePosition = true; // cannot see a way to set the Home Position in VISCA, only Goto Home available.
      this.numPresets = 6; // Old EVI-D70 has 6 presets. New models have 64 presets
      if ('PTZNumPresets' in config) this.numPresets = Number(config.PTZNumPresets)
    }
  }


  // Writes a line to a rposascii controller. cam=N is added when data has a cameraAddress.
  private rposWrite(command: string, fields: (string | number)[], data: any, keys?: { [key: string]: string | number | undefined }) {
    if (!this.rposAscii) return;
    const all: { [key: string]: string | number | undefined } = {};
    if (data && data.cameraAddress !== undefined) all['cam'] = data.cameraAddress;
    if (keys) {
      for (const key of Object.keys(keys)) all[key] = keys[key];
    }
    this.rposClient.send(command, fields, all);
  }

  // Speed for the estimator: the larger of the pan and tilt speed, or 1
  private speedOf(data: any): number {
    const speeds = [Number(data.panSpeed), Number(data.tiltSpeed)].filter((v) => isFinite(v) && v > 0);
    return speeds.length > 0 ? Math.max.apply(null, speeds) : 1;
  }

  // Field of view in degrees from the controller, or from the config as a fallback
  getFov(): { h: number, v: number } | null {
    const caps = this.rposClient ? this.rposClient.caps : null;
    const h = (caps && caps.hfov) || Number(this.config.PTZHorizontalFOV) || 0;
    const v = (caps && caps.vfov) || Number(this.config.PTZVerticalFOV) || 0;
    return (h > 0 && v > 0) ? { h: h, v: v } : null;
  }

  // Normalised units for the estimator. A translation in FOV units needs the field of view.
  private toNormalised(value: number, space: string, axis: 'h' | 'v'): number {
    if (space !== 'fov') return value;
    const fov = this.getFov();
    if (!fov) return value;
    return axis === 'h' ? (value * fov.h) / PAN_SCALE_DEG : (value * fov.v) / TILT_SCALE_DEG;
  }

  private applyCaps(caps: any) {
    this.supportsAbsolutePTZ = caps.abs;
    this.supportsRelativePTZ = caps.rel;
    this.supportsContinuousPTZ = caps.cont;
    this.supportsGoToHome = caps.home;
    this.hasFixedHomePosition = caps.fixedhome;
    this.hasZoom = caps.zoom;
    if (caps.presets > 0) this.numPresets = caps.presets;
    console.log('PTZ Driver - controller capabilities received');
    this.events.emit('capabilities', caps);
  }

  // Where ONVIF GetStatus gets its answer
  statusSource(): 'controller' | 'estimate' | 'none' {
    if (!this.rposAscii) return 'none';
    const mode = String(this.config.PTZStatusMode || 'auto').toLowerCase();
    if (mode === 'off') return 'none';
    if (mode === 'controller') return 'controller';
    if (mode === 'estimate') return 'estimate';
    const caps = this.rposClient.caps;
    return (caps && caps.movestatus) ? 'controller' : 'estimate';
  }

  supportsMoveStatus(): boolean {
    return this.statusSource() !== 'none';
  }

  // The position is only real when the controller reports it
  supportsStatusPosition(): boolean {
    const caps = this.rposClient ? this.rposClient.caps : null;
    return this.statusSource() === 'controller' && !!(caps && caps.position);
  }

  // Resolves to the PTZ status, or null when there is nothing to report
  getStatus(): Promise<PTZStatusInfo | null> {
    const source = this.statusSource();
    if (source === 'controller') {
      return this.rposClient.getStatus().then((status) => {
        if (!status) return null;
        const hasPosition = !!(this.rposClient.caps && this.rposClient.caps.position);
        return <PTZStatusInfo>{
          pan: hasPosition ? status.pan : undefined,
          tilt: hasPosition ? status.tilt : undefined,
          zoom: hasPosition ? status.zoom : undefined,
          panTilt: status.panTilt,
          error: status.error,
          estimated: false
        };
      });
    }
    if (source === 'estimate') {
      const status = this.estimator.snapshot();
      return Promise.resolve(<PTZStatusInfo>{ panTilt: status.panTilt, estimated: true });
    }
    return Promise.resolve(null);
  }

// Data messages have the following format
//   command
//   OR
//   command data
// 
//   Data can contain one or more of the following fields 
//     name:
//     value:
//     pan:
//     tilt:
//     zoom:
// JSON is used so that spaces and commas in names (eg Preset Names) is supported

// Use 'arrow functions' (instead of bind) to ensure the 'this' refers to the
// class and not to the caller's 'this'. This is required when process_ptz_command
// is used in a callback function.
  process_ptz_command = (command: string, data: any) => {
    if (command==='gotohome') {
      console.log("Goto Home");
      this.rposWrite(command, [], data);
      if (this.rposAscii) this.estimator.home();
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.sendGotoPreset(1); // use preset 1 for Home
      }
      if (this.visca) {
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        let viscaData: number[] = [];
        viscaData.push(viscaDestinationByte,0x01,0x06,0x04,0xff);
        this.stream.write(Buffer.from(viscaData));
      }
      if (this.panTiltHat) {
        this.panTiltHat.goto_home();
      }
    }
    else if (command==='sethome') {
      console.log("SetHome ");
      this.rposWrite(command, [], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.sendSetPreset(1); // use preset 1 for Home
      }
    }
    else if (command==='gotopreset') {
      console.log("Goto Preset "+ data.name + ' / ' + data.value);
      this.rposWrite(command, [data.name, data.value], data);
      if (this.tenx) this.tenx.fire();
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.sendGotoPreset(parseInt(data.value));
      }
      if (this.visca) {
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        const viscaPresetNumber = parseInt(data.value) - 1; // values start at 0
        let viscaData: number[] = [];
        viscaData.push(viscaDestinationByte,0x01,0x04,0x3f,0x02,viscaPresetNumber, 0xff);
        this.stream.write(Buffer.from(viscaData));
      }
    }
    else if (command==='setpreset') {
      console.log("Set Preset "+ data.name + ' / ' + data.value);
      this.rposWrite(command, [data.name, data.value], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.sendSetPreset(parseInt(data.value));
      }
      if (this.visca) {
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        const viscaPresetNumber = parseInt(data.value) - 1; // values start at 0 for visca
        let viscaData: number[] = [];
        viscaData.push(viscaDestinationByte,0x01,0x04,0x3f,0x01,viscaPresetNumber, 0xff);
        this.stream.write(Buffer.from(viscaData));
      }

    }
    else if (command==='clearpreset') {
      console.log("Clear Preset "+ data.name + ' / ' + data.value);
      this.rposWrite(command, [data.name, data.value], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.sendClearPreset(parseInt(data.value));
      }
    }
    else if (command==='aux') {
      console.log("Aux "+ data.name);
      this.rposWrite(command, [data.name], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        if (data.name === 'AUX1on') this.pelcod.sendSetAux(1);
        if (data.name === 'AUX1off') this.pelcod.sendClearAux(1);
        if (data.name === 'AUX2on') this.pelcod.sendSetAux(2);
        if (data.name === 'AUX2off') this.pelcod.sendClearAux(2);
        if (data.name === 'AUX3on') this.pelcod.sendSetAux(3);
        if (data.name === 'AUX3off') this.pelcod.sendClearAux(3);
        if (data.name === 'AUX4on') this.pelcod.sendSetAux(4);
        if (data.name === 'AUX4off') this.pelcod.sendClearAux(4);
        if (data.name === 'AUX5on') this.pelcod.sendSetAux(5);
        if (data.name === 'AUX5off') this.pelcod.sendClearAux(5);
        if (data.name === 'AUX6on') this.pelcod.sendSetAux(6);
        if (data.name === 'AUX6off') this.pelcod.sendClearAux(6);
        if (data.name === 'AUX7on') this.pelcod.sendSetAux(7);
        if (data.name === 'AUX7off') this.pelcod.sendClearAux(7);
        if (data.name === 'AUX8on') this.pelcod.sendSetAux(8);
        if (data.name === 'AUX8off') this.pelcod.sendClearAux(8);
      }
    }
    else if (command==='relayactive') {
      console.log("Relay Active "+ data.name);
      this.rposWrite(command, [data.name], data);
    }
    else if (command==='relayinactive') {
      console.log("Relay Inactive "+ data.name);
      this.rposWrite(command, [data.name], data);
    }
    else if (command==='stop') {
      // Stop everything that moves, including a relative or absolute move in progress.
      // data.zoom is the zoom velocity to keep when only Pan/Tilt is being stopped.
      console.log("Stop [Cam " + data.cameraAddress + "]");
      const keepZoom = parseFloat(data.zoom) || 0;
      if (this.rposAscii && this.rposClient.caps) {
        // a v2 controller has a stop message
        this.rposWrite('stop', [], data, { pantilt: 1, zoom: data.stopZoom ? 1 : undefined });
        this.estimator.stop();
      } else {
        // v1 controllers and the other drivers treat a zero velocity as stop
        this.process_ptz_command('ptz', { pan: 0, tilt: 0, zoom: keepZoom, cameraAddress: data.cameraAddress });
      }
    }
    else if (command==='ptz') {
      console.log("Continuous PTZ [Cam " + data.cameraAddress + "] " + data.pan + '\t' + data.tilt + '\t' + data.zoom + '\n');
      var p=0.0;
      var t=0.0;
      var z=0.0;
      try {p = parseFloat(data.pan)} catch (err) {}
      try {t = parseFloat(data.tilt)} catch (err) {}
      try {z = parseFloat(data.zoom)} catch (err) {}
      if (this.rposAscii) {
        this.rposWrite(command, [p, t, z], data);
        if (p === 0 && t === 0) this.estimator.stop(); else this.estimator.continuous(p, t);
      }
      if (this.tenx) {
        if      (p < -0.1 && t >  0.1) this.tenx.upleft();
        else if (p >  0.1 && t >  0.1) this.tenx.upright();
        else if (p < -0.1 && t < -0.1) this.tenx.downleft();
        else if (p >  0.1 && t < -0.1) this.tenx.downright();
        else if (p >  0.1) this.tenx.right();
        else if (p < -0.1) this.tenx.left();
        else if (t >  0.1) this.tenx.up();
        else if (t < -0.1) this.tenx.down()
        else this.tenx.stop();
      }
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.up(false).down(false).left(false).right(false);
        if      (p < 0 && t > 0) this.pelcod.up(true).left(true);
        else if (p > 0 && t > 0) this.pelcod.up(true).right(true);
        else if (p < 0 && t < 0) this.pelcod.down(true).left(true);
        else if (p > 0 && t < 0) this.pelcod.down(true).right(true);
        else if (p > 0) this.pelcod.right(true);
        else if (p < 0) this.pelcod.left(true);
        else if (t > 0) this.pelcod.up(true);
        else if (t < 0) this.pelcod.down(true);

        // Set Pan/Tilt speed
        // scale speeds from 0..1 to 0..63
        var pan_speed = Math.round(Math.abs(p) * 63.0 );
        var tilt_speed = Math.round(Math.abs(t) * 63.0 );

        this.pelcod.setPanSpeed(pan_speed);
        this.pelcod.setTiltSpeed(tilt_speed);


        this.pelcod.zoomIn(false).zoomOut(false);
        if (z>0) this.pelcod.zoomIn(true);
        if (z<0) this.pelcod.zoomOut(true);

        // Set Zoom speed
        // scale speeds from 0..1 to 0 (slow), 1 (low med), 2 (high med), 3 (fast)
        var abs_z = Math.abs(z);
        var zoom_speed = 0;
        if (abs_z > 0.75) zoom_speed = 3;
        else if (abs_z > 0.5) zoom_speed = 2;
        else if (abs_z > 0.25) zoom_speed = 1;
        else zoom_speed = 0;

        // sendSetZoomSpeed is not in node-pelcod yet so wrap with try/catch
        try {
          if (z != 0) this.pelcod.sendSetZoomSpeed(zoom_speed);
        } catch (err) {}

        this.pelcod.send();
      }
      if (this.visca) {
        // Map ONVIF Pan and Tilt Speed 0 to 1 to VISCA Speed 1 to 0x18
        // Map ONVIF Zoom Speed (0 to 1) to VISCA Speed 0 to 7
        let visca_pan_speed = ( Math.abs(p) * 0x18) / 1.0;
        let visca_tilt_speed = ( Math.abs(t) * 0x18) / 1.0;
        let visca_zoom_speed = ( Math.abs(z) * 0x07) / 1.0;

        // rounding check. Visca Pan/Tilt to be in range 0x01 .. 0x18
        if (visca_pan_speed === 0) visca_pan_speed = 1;
        if (visca_tilt_speed === 0) visca_tilt_speed = 1;

        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07) // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long

        if (this.config.PTZDriver === 'visca') {
          let viscaData: number[] = [];
          if      (p < 0 && t > 0) { // upleft
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,visca_zoom_speed,0x01,0x01,0xff);
          }
          else if (p > 0 && t > 0) { // upright
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,visca_zoom_speed,0x02,0x01,0xff);
          }
          else if (p < 0 && t < 0) { // downleft;
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,visca_zoom_speed,0x01,0x02,0xff);
          }
          else if (p >  0 && t < 0) { // downright;
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,visca_zoom_speed,0x02,0x02,0xff);
          }
          else if (p > 0) { // right
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,0x00,0x02,0x03,0xff);
          }
          else if (p < 0) { // left
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,visca_pan_speed,0x00,0x01,0x03,0xff);
          }
          else if (t > 0) { // up
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,0x00,visca_tilt_speed,0x03,0x01,0xff);
          }
          else if (t < 0) { // down
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,0x00,visca_tilt_speed,0x03,0x02,0xff);
          }
          else { // stop 
            viscaData.push(viscaDestinationByte,0x01,0x06,0x01,0x00,0x00,0x03,0x03,0xff);
          }

          // Zoom
          if (z < 0) { // zoom out
            viscaData.push(viscaDestinationByte,0x01,0x04,0x07,(0x30 + visca_zoom_speed),0xff);
          }
          else if (z > 0) { // zoom in
            viscaData.push(viscaDestinationByte,0x01,0x04,0x07,(0x20 + visca_zoom_speed),0xff);
          } else { // zoom stop
            viscaData.push(viscaDestinationByte,0x01,0x04,0x07,0x00,0xff);
          }

          this.stream.write(Buffer.from(viscaData));
        }
      }
      if (this.panTiltHat) {
        // Map ONVIF Pan and Tilt Speed 0 to 1 to Speed 0 to 15
        let pan_speed  = ( Math.abs(p) * 15) / 1.0;
        let tilt_speed = ( Math.abs(t) * 15) / 1.0;

        // rounding check.
        if (pan_speed > 15) pan_speed = 15;
        if (tilt_speed > 15) tilt_speed = 15;
        if (pan_speed < 0) pan_speed = 0;
        if (tilt_speed < 0) tilt_speed = 0;

        if (p < 0)  this.panTiltHat.pan_left(pan_speed);
        if (p > 0)  this.panTiltHat.pan_right(pan_speed);
        if (p == 0) this.panTiltHat.pan_right(0); // stop
        if (t < 0)  this.panTiltHat.tilt_down(tilt_speed);
        if (t > 0)  this.panTiltHat.tilt_up(tilt_speed);
        if (t == 0) this.panTiltHat.tilt_down(0); // stop
      }
    }
    else if (command==='absolute-ptz') {
      console.log("Absolute PTZ "+ data.pan + '\t' + data.tilt + '\t' + data.zoom);
      var p=0.0;
      var t=0.0;
      var z=0.0;
      try {p = parseFloat(data.pan)} catch (err) {}
      try {t = parseFloat(data.tilt)} catch (err) {}
      try {z = parseFloat(data.zoom)} catch (err) {}
      if (this.rposAscii) {
        this.rposWrite(command, [p, t, z], data, { panspeed: data.panSpeed, tiltspeed: data.tiltSpeed });
        this.estimator.absolute(p, t, this.speedOf(data));
      }
      if (this.panTiltHat) {
          let new_pan_angle = p * 90.0
          this.panTiltHat.pan(Math.round(new_pan_angle));
          
          let new_tilt_angle = t * 80.0
          this.panTiltHat.tilt(Math.round(new_tilt_angle));
      }
    }
    else if (command==='relative-ptz') {
      console.log("Relative PTZ "+ data.pan + '\t' + data.tilt + '\t' + data.zoom);
      var p=0.0;
      var t=0.0;
      var z=0.0;
      try {p = parseFloat(data.pan)} catch (err) {}
      try {t = parseFloat(data.tilt)} catch (err) {}
      try {z = parseFloat(data.zoom)} catch (err) {}
      if (this.rposAscii) {
        const space = (data.space === 'fov') ? 'fov' : 'generic';
        this.rposWrite(command, [p, t, z], data, { space: space, panspeed: data.panSpeed, tiltspeed: data.tiltSpeed });
        this.estimator.relative(this.toNormalised(p, space, 'h'), this.toNormalised(t, space, 'v'), this.speedOf(data));
      }
      if (this.panTiltHat) {
          let pan_degrees = p * 90.0
          let new_pan_angle = this.panTiltHat.pan_position - pan_degrees;
          this.panTiltHat.pan(Math.round(new_pan_angle));
          
          let tilt_degrees = t * 80.0
          let new_tilt_angle = this.panTiltHat.tilt_position - tilt_degrees;
          this.panTiltHat.tilt(Math.round(new_tilt_angle));
      }
    }
    else if (command==='brightness') {
      console.log("Set Brightness "+ data.value);
      this.rposWrite(command, [data.value], data);
      v4l2ctl.SetBrightness(data.value);
    }
    else if (command==='focus') {
      console.log("Focus "+ data.value);
      this.rposWrite(command, [data.value], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        if (data.value < 0) this.pelcod.focusNear(true);
        else if (data.value > 0) this.pelcod.focusFar(true);
        else {
          this.pelcod.focusNear(false);
          this.pelcod.focusFar(false);
        }
        this.pelcod.send();
      }
      if (this.visca) {
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        let viscaData: number[] = [];
        if (data.value < 0) viscaData.push(viscaDestinationByte,0x01,0x04,0x08,0x03,0xff); // focus Near
        else if (data.value > 0) viscaData.push(viscaDestinationByte,0x01,0x04,0x08,0x02,0xff); // focus Far
        else viscaData.push(viscaDestinationByte,0x01,0x04,0x08,0x00,0xff); // stop
        this.stream.write(Buffer.from(viscaData));
      }
    }
    else if (command==='focusstop') {
      console.log("Focus Stop");
      this.rposWrite(command, [], data);
      if (this.pelcod) {
        this.pelcod.setAddress(data.cameraAddress);
        this.pelcod.focusNear(false);
        this.pelcod.focusFar(false);
        this.pelcod.send();
      }
      if (this.visca) {
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        let viscaData: number[] = [];
        viscaData.push(viscaDestinationByte,0x01,0x04,0x08,0x00,0xff);
        this.stream.write(Buffer.from(viscaData));
      }
    }
    else if (command==='focusmode') {
      console.log("Focus Mode " + data.value);
      this.rposWrite(command, [], data);
      if (this.visca) {
        const valueUpper = data.value.toString().toUpperCase();
        const viscaDestinationByte = 0x80 + (data.cameraAddress & 0x07); // Encodes Sending from Device #0 as a normal (not broadcast) packet. Cammera Address is 3 bits long
        let viscaData: number[] = [];
        if (valueUpper == "AUTO") {
          viscaData.push(viscaDestinationByte,0x01,0x04,0x38,0x02,0xff);
        }
        if (valueUpper == "MANUAL") {
          viscaData.push(viscaDestinationByte,0x01,0x04,0x38,0x03,0xff);
        }

        // Note there is also a VISCA Command to toggle between Auto and Manual 8x 01 04 38 10 FF
        this.stream.write(Buffer.from(viscaData));
      }
    }
    else {
      if ('value' in data == false) {
        console.log("Unhandled PTZ/Imaging Command Received: " + command);
      } else {
        console.log("Unhandled PTZ/Imaging Command Received: " + command + ' Value:' + data.value);
      }
    }
  }
}

export = PTZDriver;
